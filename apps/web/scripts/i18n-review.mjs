// Writes docs/i18n-review.md: every Kinyarwanda string with its English source and review status.
// A string counts as reviewed only when its key is in messages/rw-reviewed.json.
//   node scripts/i18n-review.mjs          write the file
//   node scripts/i18n-review.mjs --check  fail if it is out of date
import { readFileSync, writeFileSync } from "node:fs";

const read = (path) => JSON.parse(readFileSync(path, "utf8"));
const en = read("messages/en.json");
const rw = read("messages/rw.json");
const reviewed = new Set(read("messages/rw-reviewed.json"));
const flat = (tree, prefix = "") =>
  Object.entries(tree).flatMap(([k, v]) =>
    typeof v === "object" ? flat(v, `${prefix}${k}.`) : [[`${prefix}${k}`, v]],
  );
const english = Object.fromEntries(flat(en));
const rows = flat(rw);
const pending = rows.filter(([key]) => !reviewed.has(key)).length;
const cell = (text) => String(text).replaceAll("|", "\\|").replaceAll("\n", " ");

const doc = [
  "# Kinyarwanda review list",
  "",
  "Generated by `apps/web/scripts/i18n-review.mjs`. Do not edit by hand.",
  "",
  "Every Kinyarwanda string in the web app was drafted by the development team and must be",
  "checked by a fluent reviewer before the app is used with real users. Nothing here was machine",
  "translated silently: until a key is marked reviewed (listed in",
  '`apps/web/messages/rw-reviewed.json`), the app shows a "draft translation" label in Kinyarwanda mode.',
  "",
  "Kinyarwanda text also comes from the API: alert reasons and suggestion explanations",
  "(`packages/engine/src/irerero_engine/explain.py`), driver labels",
  "(`packages/engine/src/irerero_engine/features.py`) and assistant answers",
  "(`packages/engine/src/irerero_engine/assistant.py`). Those templates need the same review.",
  "",
  `Status: ${rows.length - pending} of ${rows.length} strings reviewed.`,
  "",
  "| Key | English | Kinyarwanda draft | Reviewed |",
  "| --- | --- | --- | --- |",
  ...rows.map(
    ([key, value]) =>
      `| \`${key}\` | ${cell(english[key] ?? "")} | ${cell(value)} | ${reviewed.has(key) ? "yes" : "no"} |`,
  ),
  "",
].join("\n");

const target = "../../docs/i18n-review.md";
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== doc) {
    console.error("docs/i18n-review.md is out of date: run pnpm --filter web i18n:review");
    process.exit(1);
  }
} else {
  writeFileSync(target, doc);
}
